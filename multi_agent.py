from typing import TypedDict
from langgraph.graph import StateGraph, END
from langchain_core.messages import HumanMessage
from langchain_ollama import ChatOllama
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_chroma import Chroma

# Import the vision tool you built in Phase 2
from vision_tool import analyze_chest_xray

print("⚙️ Initializing Multi-Agent Clinical System...")

# 1. Define the Shared State (The memory object passed between agents)
class ClinicalState(TypedDict):
    patient_query: str
    image_path: str
    vision_findings: str
    literature_context: str
    final_report: str

# 2. Initialize Shared Resources
llm = ChatOllama(model="llama3.1", temperature=0)
embeddings = HuggingFaceEmbeddings(
    model_name="sentence-transformers/all-MiniLM-L6-v2", 
    model_kwargs={'device': 'cpu'}
)
vector_store = Chroma(persist_directory="./clinical_db", embedding_function=embeddings)
retriever = vector_store.as_retriever(search_kwargs={"k": 2})

# 3. Define the Agents (Nodes)

def vision_agent(state: ClinicalState):
    print("  -> [Vision Agent] Analyzing pixel data...")
    findings = analyze_chest_xray.invoke({"image_path": state["image_path"]})
    return {"vision_findings": findings}

def literature_agent(state: ClinicalState):
    print("  -> [Literature Agent] Querying RAG database for findings...")
    # Search the DB using the exact findings generated by the Vision Agent
    docs = retriever.invoke(state["vision_findings"])
    context = "\n\n".join([d.page_content for d in docs])
    return {"literature_context": context}

def diagnosis_agent(state: ClinicalState):
    print("  -> [Diagnosis Agent] Synthesizing differential diagnosis...")
    prompt = f"""
    You are an expert diagnostic radiologist. Based on the following inputs, generate a structured differential diagnosis report.
    
    Patient Query: {state['patient_query']}
    Image Findings: {state['vision_findings']}
    Clinical Literature: {state['literature_context']}
    
    Provide the top 3 most likely diagnoses, ranked by probability, with a brief justification for each based strictly on the literature provided.
    """
    response = llm.invoke([HumanMessage(content=prompt)])
    return {"final_report": response.content}

# 4. Build the LangGraph Workflow
workflow = StateGraph(ClinicalState)

# Add the agents to the graph
workflow.add_node("vision_node", vision_agent)
workflow.add_node("literature_node", literature_agent)
workflow.add_node("diagnosis_node", diagnosis_agent)

# Define the sequential flow
workflow.set_entry_point("vision_node")
workflow.add_edge("vision_node", "literature_node")
workflow.add_edge("literature_node", "diagnosis_node")
workflow.add_edge("diagnosis_node", END)

# Compile the system
app = workflow.compile()

# 5. Execute a Case
if __name__ == "__main__":
    print("\n🚀 Starting Case Analysis...")
    initial_state = {
        "patient_query": "Patient presents with shortness of breath. Please review the X-ray for abnormalities and provide a DDx.",
        "image_path": "dummy_xray.png",
        "vision_findings": "",
        "literature_context": "",
        "final_report": ""
    }
    
    # Run the graph
    result = app.invoke(initial_state)
    
    print("\n================ FINAL RADIOLOGY REPORT ================\n")
    print(result["final_report"])